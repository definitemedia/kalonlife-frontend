function replaceJsonValue(text, oldValue, newValue) {
  if (oldValue === newValue) return text;
  const needle = JSON.stringify(oldValue);
  const replacement = JSON.stringify(newValue);
  const titleNeedle = `"title": ${needle}`;
  const titleHits = text.split(titleNeedle).length - 1;
  if (titleHits === 1) {
    return text.replace(titleNeedle, `"title": ${replacement}`);
  }
  const hits = text.split(needle).length - 1;
  if (hits === 1) {
    return text.replace(needle, replacement);
  }
  if (hits === 0 && text.includes(replacement)) return text;
  throw new Error(
    `cannot uniquely replace ${oldValue} (title hits ${titleHits}, raw hits ${hits})`,
  );
}

function appendTerms(text, terms) {
  const nl = text.includes("\r\n") ? "\r\n" : "\n";
  const body = JSON.stringify(terms, null, 2).replace(/\n/g, nl);
  const indented = body
    .split(nl)
    .map((line, index) => (index === 0 ? line : `  ${line}`))
    .join(nl);
  const trimmed = text.trimEnd();
  if (!trimmed.endsWith("}")) {
    throw new Error("file does not end with }");
  }
  return `${trimmed.slice(0, -1)},${nl}  "terms": ${indented}${nl}}`;
}

for (const [locale, terms] of Object.entries(copy)) {
  const file = new URL(`${locale}.json`, messagesDir);
  const beforeText = fs.readFileSync(file, "utf8");
  const before = JSON.parse(beforeText);
  if (!before.routes?.terms?.title || !before.routes?.terms?.description) {
    throw new Error(`${locale}: missing routes.terms`);
  }
  if (before.terms) {
    throw new Error(`${locale}: terms namespace already exists`);
  }

  let next = beforeText;
  next = replaceJsonValue(next, before.routes.terms.description, terms.subtitle);
  next = replaceJsonValue(next, before.routes.terms.title, terms.title);
  next = appendTerms(next, terms);

  const after = JSON.parse(next);
  const beforeKeys = Object.keys(before);
  const afterKeys = Object.keys(after);
  const added = afterKeys.filter((key) => !beforeKeys.includes(key));
  const removed = beforeKeys.filter((key) => !afterKeys.includes(key));
  if (added.join() !== "terms" || removed.length) {
    throw new Error(`${locale}: key drift added=${added} removed=${removed}`);
  }

  const beforeCheck = structuredClone(before);
  const afterCheck = structuredClone(after);
  delete afterCheck.terms;
  beforeCheck.routes.terms.title = terms.title;
  beforeCheck.routes.terms.description = terms.subtitle;
  if (JSON.stringify(beforeCheck) !== JSON.stringify(afterCheck)) {
    throw new Error(`${locale}: unexpected changes outside terms`);
  }
  if (after.routes.terms.description !== terms.subtitle) {
    throw new Error(`${locale}: description was not updated`);
  }
  if (!String(after.terms.intro).includes("Kalonlife International India Private Limited")) {
    throw new Error(`${locale}: legal name missing`);
  }

  fs.writeFileSync(file, next.endsWith("\n") ? next : `${next}\n`);
  console.log(`updated ${locale}.json`);
}
