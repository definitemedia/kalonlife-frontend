function newlineOf(raw) {
  return raw.includes("\r\n") ? "\r\n" : "\n";
}

function withNewlines(text, newline) {
  return newline === "\n" ? text : text.replace(/\n/g, newline);
}

function stringifyIndented(value, baseIndent) {
  const json = JSON.stringify(value, null, 2);
  const pad = " ".repeat(baseIndent);
  return json
    .split("\n")
    .map((line, index) => (index === 0 ? line : pad + line))
    .join("\n");
}

function skipValue(raw, start) {
  let i = start;
  while (i < raw.length && /\s/.test(raw[i])) i += 1;
  const ch = raw[i];
  if (ch === '"') {
    i += 1;
    while (i < raw.length) {
      if (raw[i] === "\\") {
        i += 2;
        continue;
      }
      if (raw[i] === '"') return i + 1;
      i += 1;
    }
    throw new Error("unterminated string");
  }
  if (ch === "{" || ch === "[") {
    const open = ch;
    const close = ch === "{" ? "}" : "]";
    let depth = 0;
    let inString = false;
    for (; i < raw.length; i += 1) {
      const current = raw[i];
      if (inString) {
        if (current === "\\") {
          i += 1;
          continue;
        }
        if (current === '"') inString = false;
        continue;
      }
      if (current === '"') {
        inString = true;
        continue;
      }
      if (current === open) depth += 1;
      else if (current === close) {
        depth -= 1;
        if (depth === 0) return i + 1;
      }
    }
    throw new Error("unterminated value");
  }
  throw new Error(`unsupported value at ${start}`);
}

function findTopLevelProperty(raw, key) {
  let i = 0;
  while (i < raw.length && raw[i] !== "{") i += 1;
  i += 1;
  let depth = 1;
  while (i < raw.length && depth > 0) {
    const ch = raw[i];
    if (ch === '"') {
      const keyStart = i;
      i += 1;
      let name = "";
      while (i < raw.length) {
        if (raw[i] === "\\") {
          name += raw[i + 1];
          i += 2;
          continue;
        }
        if (raw[i] === '"') {
          i += 1;
          break;
        }
        name += raw[i];
        i += 1;
      }
      if (depth === 1) {
        let j = i;
        while (j < raw.length && /\s/.test(raw[j])) j += 1;
        if (raw[j] === ":" && name === key) {
          j += 1;
          while (j < raw.length && /\s/.test(raw[j])) j += 1;
          return { keyStart, valueStart: j, valueEnd: skipValue(raw, j) };
        }
      }
      continue;
    }
    if (ch === "{" || ch === "[") depth += 1;
    else if (ch === "}" || ch === "]") depth -= 1;
    i += 1;
  }
  return null;
}

function deepEqual(left, right) {
  if (left === right) return true;
  if (!left || !right || typeof left !== "object" || typeof right !== "object") return false;
  const leftKeys = Object.keys(left);
  const rightKeys = Object.keys(right);
  if (leftKeys.length !== rightKeys.length) return false;
  return leftKeys.every((key) => deepEqual(left[key], right[key]));
}

function transform(raw, description, body) {
  const before = JSON.parse(raw);
  if (!before.routes?.disclaimer || typeof before.routes.disclaimer.description !== "string") {
    throw new Error("missing routes.disclaimer.description");
  }

  const newline = newlineOf(raw);
  let next = raw;
  const current = before.routes.disclaimer.description;
  if (current !== description) {
    const needle = JSON.stringify(current);
    const replacement = JSON.stringify(description);
    const count = next.split(needle).length - 1;
    if (count !== 1) {
      throw new Error(`description appears ${count} times`);
    }
    next = next.split(needle).join(replacement);
  }

  const parsed = JSON.parse(next);
  const existing =
    parsed.disclaimerBody && typeof parsed.disclaimerBody === "object" && !Array.isArray(parsed.disclaimerBody)
      ? parsed.disclaimerBody
      : null;
  const merged = { ...(existing ?? {}), ...body };

  if (!existing) {
    const block = `  "disclaimerBody": ${stringifyIndented(merged, 2)}`;
    const trimmed = next.replace(/\s*$/, "");
    const last = trimmed.lastIndexOf("}");
    const head = trimmed.slice(0, last).replace(/\s*$/, "");
    next = `${head},${newline}${withNewlines(block, newline)}${newline}}${newline}`;
  } else if (!deepEqual(existing, merged)) {
    const found = findTopLevelProperty(next, "disclaimerBody");
    if (!found) throw new Error("could not locate disclaimerBody");
    const rendered = withNewlines(stringifyIndented(merged, 2), newline);
    next = next.slice(0, found.valueStart) + rendered + next.slice(found.valueEnd);
  }

  const after = JSON.parse(next);
  const expected = structuredClone(before);
  expected.routes.disclaimer.description = description;
  expected.disclaimerBody = { ...(expected.disclaimerBody ?? {}), ...body };
  if (!deepEqual(expected, after)) {
    throw new Error("update changed or dropped unrelated keys");
  }
  return next;
}

for (const [locale, content] of Object.entries(locales)) {
  const file = path.join(root, "messages", `${locale}.json`);
  let written = false;
  for (let attempt = 0; attempt < 8; attempt += 1) {
    const raw = fs.readFileSync(file, "utf8");
    const updated = transform(raw, content.description, content.body);
    if (fs.readFileSync(file, "utf8") !== raw) continue;
    if (updated !== raw) fs.writeFileSync(file, updated);
    if (fs.readFileSync(file, "utf8") === updated) {
      written = true;
      break;
    }
  }
  if (!written) throw new Error(`could not update ${locale}`);
  const check = JSON.parse(fs.readFileSync(file, "utf8"));
  if (check.routes.disclaimer.description !== content.description) {
    throw new Error(`${locale} description mismatch`);
  }
  if (!deepEqual(check.disclaimerBody, { ...(check.disclaimerBody ?? {}), ...content.body })) {
    throw new Error(`${locale} body mismatch`);
  }
  console.log(`updated ${locale}`);
}
